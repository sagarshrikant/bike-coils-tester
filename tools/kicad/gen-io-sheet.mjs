#!/usr/bin/env node
// Generates hardware/kicad/mainboard/mainboard-io.kicad_sch: the Pico, the two MCP23017 expanders, the two ADS1115 module
// headers, the I2C / reset pull-ups, the expander pull resistors, the reset button and the expansion header J8.
// Every pin carries its net as a global label. Net names come from docs/pin-budget.md and hardware/circuits/mainboard.md.
// Usage: KICAD_SYMBOLS=<kicad-symbols checkout> node tools/kicad/gen-io-sheet.mjs [--nets]
import { Sheet } from './sch-lib.mjs';

const s = new Sheet('Mainboard I/O');
const R = 'Device:R', C = 'Device:C';
const R0805 = 'Resistor_SMD:R_0805_2012Metric', C0805 = 'Capacitor_SMD:C_0805_2012Metric';
const GL = 'GND_L';

// ---- net maps (pin number -> net)
const pico = {
  1: 'RLY_EN', 2: 'GP1_SPARE', 3: GL, 4: 'PU_POS', 5: 'PU_NEG', 6: 'SDA', 7: 'SCL', 8: GL, 9: 'TG_PULSE_A', 10: 'TG_PULSE_B',
  11: 'HV_CMP', 12: 'SP_IN', 13: GL, 14: 'RIG_PWM', 15: 'RIG_TACH', 16: 'DRV_OUT', 17: 'ARM_SENSE', 18: GL, 19: 'R2_DRIVE_1K',
  20: 'R2_DRIVE_10K', 21: 'GP16_SPARE', 22: 'PU_DAC_CS', 23: GL, 24: 'SPI0_SCK', 25: 'SPI0_MOSI', 26: 'EXP_RESET', 27: 'EXP_INT',
  28: GL, 29: 'PWR_EN', 30: 'RUN', 31: 'PU_SIG', 32: 'PU_PKP', 33: 'AGND', 34: 'PU_PKN', 36: '3V3', 38: GL, 39: 'VSYS', 40: 'VBUS',
};
// MCP23017: 1-8 GPB0-7, 9 VDD, 10 VSS, 11 NC, 12 SCL, 13 SDA, 14 NC, 15-17 A0-A2, 18 RESET, 19 INTB, 20 INTA, 21-28 GPA0-7
const mcp = (a, b, a0, intaNet) => {
  const m = { 9: '3V3', 10: GL, 12: 'SCL', 13: 'SDA', 15: a0 ? '3V3' : GL, 16: GL, 17: GL, 18: 'EXP_RESET' };
  if (intaNet) m[20] = intaNet;
  a.forEach((n, i) => { if (n) m[21 + i] = n; });
  b.forEach((n, i) => { if (n) m[1 + i] = n; });
  return m;
};
const exp1A = ['PU_RANGE5', 'PU_RANGE20', 'PU_RANGE100', 'PU_LOAD1', 'PU_LOAD2', 'PU_TEST', 'PU_PKRST_P', 'PU_PKRST_N'];
const exp1B = [null, null, null, null, 'TG_IMP0', 'TG_IMP1', 'TG_IMP2', 'TG_EN'];
const exp2A = ['R4_EN', 'INS_EN', 'HV_RANGE0', 'HV_RANGE1', 'HV_PKRST', 'MID_SENSE', 'R2_CAL1', 'R2_CAL2'];
const exp2B = ['KILL_GND', 'KILL_HI', null, null, null, null, null, null];
const exp1 = mcp(exp1A, exp1B, false, 'EXP_INT');
const exp2 = mcp(exp2A, exp2B, true, null);
const spare = (m, extra) => [11, 14, 19, ...extra, ...Array.from({ length: 28 }, (_, i) => i + 1).filter((n) => (n <= 8 || n >= 21) && !m[n] && !extra.includes(n))];
// ADS1115 module header, pin order confirmed: 1 VDD, 2 GND, 3 SCL, 4 SDA, 5 ADDR, 6 ALRT, 7 A0, 8 A1, 9 A2, 10 A3
const jm1 = { 1: '3V3A', 2: 'AGND', 3: 'SCL', 4: 'SDA', 5: GL, 6: 'ADS1_ALRT', 7: 'V_NODE', 8: 'V_TOP1K', 9: 'V_TOP10K', 10: 'ADS1_A3_SPARE' };
const jm2 = { 1: '3V3_P', 2: 'GND_P', 3: 'SCL_P', 4: 'SDA_P', 5: '3V3_P', 6: 'ADS2_ALRT', 7: 'V_OUT_M', 8: 'V_AMPP_M', 9: 'V_AMPN_M', 10: 'V_ARM_M' };
// J8 expansion header, odd/even numbering
const j8 = { 1: '3V3', 2: GL, 3: 'SDA', 4: 'SCL', 5: 'GP1_SPARE', 6: 'HV_CMP', 7: 'SP_IN', 8: 'RIG_PWM', 9: 'RIG_TACH', 10: 'DRV_OUT', 11: 'GP16_SPARE', 12: 'EXP_INT', 13: 'VSYS', 14: GL };

s.note(10, 8, 'Mainboard I/O sheet (generated): Pico, expanders, ADS1115 module headers, pull resistors, reset, J8', 2.54);
s.note(10, 16, 'Every pin has its net as a global label (docs/pin-budget.md). Generated by tools/kicad/gen-io-sheet.mjs: change the pin map, then regenerate. References are in the 300 series (U1, U2, U3, JM1, JM2, J8 as on the block pages).');

// ---- main parts
const PX = 90, PY = 115, E1X = 200, E1Y = 115, E2X = 290, E2Y = 115;
s.place({ libId: 'MCU_Module:RaspberryPi_Pico_W', ref: 'U1', value: 'Raspberry Pi Pico 2 W', footprint: 'Module:RaspberryPi_Pico_Common_THT', x: PX, y: PY, nets: pico, nc: [35, 37] });
s.place({ libId: 'Interface_Expansion:MCP23017x-x-SP', ref: 'U2', value: 'MCP23017-E/SP (EXP1, 0x20)', footprint: 'Package_DIP:DIP-28_W7.62mm', x: E1X, y: E1Y, nets: exp1, nc: spare(exp1, [20].filter((n) => !exp1[n])) });
s.place({ libId: 'Interface_Expansion:MCP23017x-x-SP', ref: 'U3', value: 'MCP23017-E/SP (EXP2, 0x21)', footprint: 'Package_DIP:DIP-28_W7.62mm', x: E2X, y: E2Y, nets: exp2, nc: spare(exp2, [20]) });
s.note(E1X - 20, E1Y + 38, 'U2 = EXP1 (0x20): A0-A2 to GND_L, INTA to EXP_INT. Spare: B0-B3.');
s.note(E2X - 20, E2Y + 38, 'U3 = EXP2 (0x21): A0 to 3V3, A1-A2 to GND_L. Spare: B2-B7.');

// ---- bus pull-ups, reset, decoupling, reset button (row y = 165)
s.box(8, 158, 420, 16);
s.note(10, 159, 'Bus and reset');
s.two(R, 'R301', '4.7k (SDA pull-up)', R0805, 40, 168, '3V3', 'SDA');
s.two(R, 'R302', '4.7k (SCL pull-up)', R0805, 85, 168, '3V3', 'SCL');
s.two(R, 'R303', '10k (EXP_RESET pull-up)', R0805, 130, 168, '3V3', 'EXP_RESET');
s.two(C, 'C301', '100n (U2)', C0805, 185, 168, '3V3', GL);
s.two(C, 'C302', '100n (U3)', C0805, 225, 168, '3V3', GL);
s.place({ libId: 'Switch:SW_Push', ref: 'SW_RST', value: 'RUN to GND (6x6 button)', footprint: 'Button_Switch_THT:SW_PUSH_6mm', x: 290, y: 168, nets: { 1: 'RUN', 2: GL } });

// ---- safe-default pull resistors on the expander outputs (10k)
s.box(8, 178, 420, 40);
s.note(10, 179, 'Expander output pull resistors (safe state while the expander is in reset). RANGE100 is pulled UP (least sensitive range); all others down.');
const pulls = [
  ...['PU_RANGE5', 'PU_RANGE20', 'PU_LOAD1', 'PU_LOAD2', 'TG_IMP0', 'TG_IMP1', 'TG_IMP2', 'TG_EN', 'R4_EN', 'INS_EN', 'R2_CAL1', 'R2_CAL2', 'KILL_GND', 'KILL_HI'].map((n) => [n, GL]),
  ['PU_RANGE100', '3V3'],
];
pulls.forEach(([net, rail], i) => {
  const col = i % 8, row = Math.floor(i / 8);
  s.two(R, `R${310 + i}`, `10k (${rail === GL ? 'down' : 'UP'})`, R0805, 30 + col * 50, 192 + row * 14, net, rail);
});

// ---- module headers and J8
s.place({ libId: 'Connector:Conn_01x10_Socket', ref: 'JM1', value: 'ADS1115 module 0x48 (logic side)', footprint: 'Connector_PinSocket_2.54mm:PinSocket_1x10_P2.54mm_Vertical', x: 70, y: 250, nets: jm1 });
s.place({ libId: 'Connector:Conn_01x10_Socket', ref: 'JM2', value: 'ADS1115 module 0x49 (12 V side)', footprint: 'Connector_PinSocket_2.54mm:PinSocket_1x10_P2.54mm_Vertical', x: 170, y: 250, nets: jm2 });
s.place({ libId: 'Connector_Generic:Conn_02x08_Odd_Even', ref: 'J8', value: 'expansion 2x8', footprint: 'Connector_PinHeader_2.54mm:PinHeader_2x08_P2.54mm_Vertical', x: 290, y: 250, nets: j8, nc: [15, 16] });
s.note(40, 272, 'JM1: pin order VDD, GND, SCL, SDA, ADDR, ALRT, A0, A1, A2, A3 (confirmed by the user). JM2 is on the 12 V side (3V3_P / GND_P); ADDR to 3V3_P gives 0x49.');
s.note(250, 272, 'J8: 1 3V3, 2 GND_L, 3 SDA, 4 SCL, 5 GP1, 6 GP8, 7 GP9, 8 GP10, 9 GP11, 10 GP12, 11 GP16, 12 GP21, 13 VSYS, 14 GND_L, 15-16 spare.');

const out = 'hardware/kicad/mainboard/mainboard-io.kicad_sch';
const size = s.write(out, 'A3');
console.log(`wrote ${out} (${size} bytes)`);
if (process.argv.includes('--nets')) for (const [n, p] of [...s.netlist].sort()) console.log(n.padEnd(14), p.join('  '));
for (const w of s.warn) console.warn('WARN', w);
