#!/usr/bin/env node
// Generates hardware/kicad/mainboard/mainboard-arm.kicad_sch: the 12 V input and ARM stage (hardware/circuits/power-arm.md)
// as a netlist-style sheet: real KiCad symbols, every pin labelled with its net.
// Usage: KICAD_SYMBOLS=<kicad-symbols checkout> node tools/kicad/gen-arm-sheet.mjs
import { Sheet } from './sch-lib.mjs';

const s = new Sheet('ARM stage');
const R = 'Device:R', C = 'Device:C', CP = 'Device:C_Polarized', LED = 'Device:LED', D = 'Device:D', TVS = 'Device:D_TVS';
const R0805 = 'Resistor_SMD:R_0805_2012Metric', C0805 = 'Capacitor_SMD:C_0805_2012Metric';
const PH = 'TerminalBlock_Phoenix:TerminalBlock_Phoenix_MKDS-1,5-';
const GP = 'GND_P', GL = 'GND_L';

// two-terminal part laid out left-right at (x, y): nets = [left net, right net]
const two = (libId, ref, value, fp, x, y, a, b) => {
  // pin 1 is at the top of an unrotated R/C/fuse, so after a 90-degree turn it is on the LEFT
  s.place({ libId, ref, value, footprint: fp, x, y, rot: 90, nets: { 1: a, 2: b } });
};
// diodes/LEDs are drawn left-right already: pin 1 = K (left), pin 2 = A (right)
const diode = (libId, ref, value, fp, x, y, anode, cathode) => {
  s.place({ libId, ref, value, footprint: fp, x, y, rot: 0, nets: { 1: cathode, 2: anode } });
};

s.note(10, 8, 'ARM stage: 12 V input, reverse protection, switch 1 (Q2), series relay (K1), sense optocouplers (generated)', 2.54);
s.note(10, 16, 'Every pin carries its net as a global label. Source: hardware/circuits/power-arm.md. Generated by tools/kicad/gen-arm-sheet.mjs: change the generator, not the labels.');
s.note(10, 21, 'References are in the 100 series so they stay unique on the mainboard. Mapping to the block page: R101 R_G1, R102 R_PU, R103 R_PD, R104 R_GQ, R105 R_SM, R106 R_S, R107 R_BL, U101 U_ARM, U102 U_RLY, U103 U_MID, U104 U_SENSE, D101 D1 (TVS), D102 D6 (flyback).');

// ---------------- connectors (left column)
s.box(8, 28, 100, 112);
s.note(10, 29, 'Connectors');
s.place({ libId: 'Connector:Screw_Terminal_01x02', ref: 'J1', value: '12 V IN (+, GND_P)', footprint: PH + '2-5.08_1x02_P5.08mm_Horizontal', x: 40, y: 45, nets: { 1: '12V_IN', 2: GP } });
s.place({ libId: 'Connector:Screw_Terminal_01x04', ref: 'J21', value: 'SW1A (1-2), SW2A E-STOP (3-4)', footprint: PH + '4-5.08_1x04_P5.08mm_Horizontal', x: 40, y: 70, nets: { 1: 'ARM_A1', 2: 'ARM_A2', 3: 'ARM_A2', 4: 'ARM_A3' } });
s.place({ libId: 'Connector:Screw_Terminal_01x04', ref: 'J22', value: 'SW1B (1-2), SW2B E-STOP (3-4)', footprint: PH + '4-5.08_1x04_P5.08mm_Horizontal', x: 40, y: 95, nets: { 1: '12V_RAW', 2: 'ARM_B2', 3: 'ARM_B2', 4: 'RLY_COIL_P' } });
s.place({ libId: 'Connector:Screw_Terminal_01x02', ref: 'J3', value: 'OUT 1: CDI POWER+', footprint: PH + '2-5.08_1x02_P5.08mm_Horizontal', x: 40, y: 117, nets: { 1: 'OUT1', 2: GP } });
s.place({ libId: 'Connector:Screw_Terminal_01x02', ref: 'J4', value: 'OUT 2 (spare)', footprint: PH + '2-5.08_1x02_P5.08mm_Horizontal', x: 40, y: 130, nets: { 1: 'OUT2', 2: GP } });

// ---------------- input protection (12V_RAW)
s.box(112, 28, 150, 70);
s.note(114, 29, 'Input: fuse, reverse protection Q1, bulk and TVS on 12V_RAW');
s.place({ libId: 'Device:Fuse', ref: 'F1', value: '5 A quick 5x20 (ESKA 520.024), holder ESKA 503101 x2', footprint: '', x: 130, y: 50, rot: 90, nets: { 1: '12V_IN', 2: 'IN_FUSED' } });
s.place({ libId: 'Transistor_FET:IRF4905', ref: 'Q1', value: 'IRF4905 (reverse protection)', footprint: 'Package_TO_SOT_THT:TO-220-3_Vertical', x: 175, y: 50, nets: { G: 'Q1_G', D: 'IN_FUSED', S: '12V_RAW' } });
two(R, 'R101', '10k (R_G1)', R0805, 215, 50, 'Q1_G', GP);
two(CP, 'C101', '470u 25V (radial 10 mm)', 'Capacitor_THT:CP_Radial_D10.0mm_P5.00mm', 130, 80, '12V_RAW', GP);
two(C, 'C102', '100n', C0805, 160, 80, '12V_RAW', GP);
s.place({ libId: TVS, ref: 'D101', value: 'SM6T18CA (supply max 14 V)', footprint: 'Diode_SMD:D_SMB', x: 190, y: 80, nets: { 1: '12V_RAW', 2: GP } });
two(R, 'R108', '2.2k (green LED)', R0805, 215, 80, '12V_RAW', 'LEDG_A');
diode(LED, 'LED101', 'green: 12 V present', 'LED_THT:LED_D3.0mm', 245, 80, 'LEDG_A', GP);

// ---------------- switch 1: Q2 and its gate chain, enable optocoupler U101
s.box(112, 102, 150, 62);
s.note(114, 103, 'Switch 1: Q2 (on only when PWR_EN, SW1A and SW2A all agree)');
s.place({ libId: 'Transistor_FET:IRF4905', ref: 'Q2', value: 'IRF4905 (switch 1)', footprint: 'Package_TO_SOT_THT:TO-220-3_Vertical', x: 135, y: 130, nets: { G: 'Q2_G', D: '12V_MID', S: '12V_RAW' } });
two(R, 'R102', '10k (R_PU)', R0805, 175, 118, '12V_RAW', 'Q2_G');
two(R, 'R103', '2.2k (R_PD)', R0805, 175, 134, 'Q2_G', 'ARM_A1');
s.place({ libId: 'Isolator:PC817', ref: 'U101', value: 'PC817 (U_ARM)', footprint: 'Package_DIP:DIP-4_W7.62mm', x: 230, y: 135, nets: { 1: 'U101_A', 2: GL, 3: GP, 4: 'ARM_A3' } });
two(R, 'R110', '330 (PWR_EN)', R0805, 195, 152, 'PWR_EN', 'U101_A');
two(R, 'R111', '10k pull-down', R0805, 235, 152, 'PWR_EN', GL);

// ---------------- 12V_MID, relay K1, 12V_ARMED, outputs
s.box(266, 28, 140, 136);
s.note(268, 29, 'Switch 2: series relay K1 (coil through SW1B/SW2B, Q3, own optocoupler U102)');
s.place({ libId: 'Relay:G5LE-1', ref: 'K1', value: 'Omron G5LE-1 DC12 (COM=12V_MID, NO=12V_ARMED, coil 2 and 5)', footprint: 'Relay_THT:Relay_SPDT_Omron-G5LE-1', x: 295, y: 60, nets: { 1: '12V_MID', 3: '12V_ARMED', 5: 'RLY_COIL_P', 2: 'RLY_COIL_N' }, nc: [4] });
diode(D, 'D102', '1N4007 (flyback)', 'Diode_THT:D_DO-41_SOD81_P10.16mm_Horizontal', 335, 60, 'RLY_COIL_N', 'RLY_COIL_P');
s.place({ libId: 'Transistor_FET:2N7000', ref: 'Q3', value: '2N7000 (relay driver)', footprint: 'Package_TO_SOT_THT:TO-92_Inline', x: 295, y: 100, nets: { D: 'RLY_COIL_N', S: GP, G: 'Q3_G' } });
two(R, 'R104', '10k (R_GQ)', R0805, 330, 100, 'Q3_G', GP);
s.place({ libId: 'Isolator:PC817', ref: 'U102', value: 'PC817 (U_RLY)', footprint: 'Package_DIP:DIP-4_W7.62mm', x: 295, y: 130, nets: { 1: 'U102_A', 2: GL, 3: 'Q3_G', 4: '12V_RAW' } });
two(R, 'R112', '330 (RLY_EN)', R0805, 330, 128, 'RLY_EN', 'U102_A');
two(R, 'R113', '10k pull-down', R0805, 330, 144, 'RLY_EN', GL);
// sense and bleed
two(R, 'R107', '4.7k 0.5W (R_BL, bleeds the rail)', 'Resistor_SMD:R_1206_3216Metric', 370, 45, '12V_ARMED', GP);
two(R, 'R109', '2.2k (red LED)', R0805, 370, 60, '12V_ARMED', 'LEDR_A');
diode(LED, 'LED102', 'red: ARMED', 'LED_THT:LED_D3.0mm', 395, 60, 'LEDR_A', GP);
s.place({ libId: 'Device:Polyfuse', ref: 'F2', value: 'SMD1812P200TF/16 (OUT 1)', footprint: 'Fuse:Fuse_1812_4532Metric', x: 370, y: 90, rot: 90, nets: { 1: '12V_ARMED', 2: 'OUT1' } });
s.place({ libId: 'Device:Polyfuse', ref: 'F3', value: 'SMD1812P200TF/16 (OUT 2)', footprint: 'Fuse:Fuse_1812_4532Metric', x: 370, y: 105, rot: 90, nets: { 1: '12V_ARMED', 2: 'OUT2' } });

// ---------------- sense optocouplers (power side LED, logic side transistor)
s.box(112, 168, 294, 54);
s.note(114, 169, 'Sense: MID_SENSE reads 12V_MID, ARM_SENSE reads the real 12V_ARMED rail (low = live). Pull-ups to 3V3 on the logic side.');
s.place({ libId: 'Isolator:PC817', ref: 'U103', value: 'PC817 (U_MID)', footprint: 'Package_DIP:DIP-4_W7.62mm', x: 150, y: 195, nets: { 1: 'U103_A', 2: GP, 3: GL, 4: 'MID_SENSE' } });
two(R, 'R105', '3.3k (R_SM)', R0805, 115, 205, '12V_MID', 'U103_A');
two(R, 'R114', '10k pull-up', R0805, 190, 205, '3V3', 'MID_SENSE');
s.place({ libId: 'Isolator:PC817', ref: 'U104', value: 'PC817 (U_SENSE)', footprint: 'Package_DIP:DIP-4_W7.62mm', x: 270, y: 195, nets: { 1: 'U104_A', 2: GP, 3: GL, 4: 'ARM_SENSE' } });
two(R, 'R106', '3.3k (R_S)', R0805, 235, 205, '12V_ARMED', 'U104_A');
two(R, 'R115', '10k pull-up', R0805, 310, 205, '3V3', 'ARM_SENSE');

s.note(10, 232, 'Isolation: U101..U104 are the only parts bridging GND_P and GND_L. Keep at least 2 mm of copper-free gap under them.');
s.note(10, 237, 'Safety: this sheet carries 12 V only. The CDI makes its own high voltage. See docs/safety.md.');

const size = s.write('hardware/kicad/mainboard/mainboard-arm.kicad_sch', 'A3');
console.log(`wrote hardware/kicad/mainboard/mainboard-arm.kicad_sch (${size} bytes)`);
if (process.argv.includes('--nets')) for (const [n, p] of [...s.netlist].sort()) console.log(n.padEnd(12), p.join('  '));
for (const w of s.warn) console.warn('WARN', w);
